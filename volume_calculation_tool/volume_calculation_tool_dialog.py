    def _setCurrentRow(self, row):
        """Make `row` the current row (info line) without changing the selection."""
        index = self.tablePolygons.model().index(row, COL_NAME)
        self.tablePolygons.selectionModel().setCurrentIndex(index, QItemSelectionModel.SelectionFlag.NoUpdate)

    def _onRowMethodChanged(self, combo):
        row = self._rowOfWidget(combo, COL_METHOD)
        if row < 0:
            return
        self.tablePolygons.cellWidget(row, COL_LEVEL).setManual(
            self._rowMethod(row) == BaseLevelOptions.MANUAL_BASE_LEVEL)
        self._markRowChanged(row)
        self._setCurrentRow(row)
        self._updateMethodInfo()
        self.updateBaseDemEnabled()

    def _onRowMethodActivated(self, combo):
        """Method chosen by the user in a row: spreadsheet-like, it is also given to the other
        selected rows when the row is part of a multi-row selection (and the info line says so);
        'Manual level' asks the level."""
        row = self._rowOfWidget(combo, COL_METHOD)
        if row < 0:
            return
        method = self._rowMethod(row)
        selected = self.selectedRows()
        others = [r for r in selected if r != row] if row in selected else []
        level = None
        if method == BaseLevelOptions.MANUAL_BASE_LEVEL:
            level = self._askLevel([row] + others)
        if others:
            self.setRowsMethod(others, method, level=level, remember=False)
        if level is not None:
            cell = self.tablePolygons.cellWidget(row, COL_LEVEL)
            cell.spin.blockSignals(True)
            cell.setValue(level)
            cell.spin.blockSignals(False)
            cell._refreshStyle()
        self._setCurrentRow(row)
        note = ""
        if others:
            note = _plural(len(others), tr("Also applied to the other selected row (ID {})."),
                           tr("Also applied to the other selected rows (ID {}).")).format(self._rowIds(others))
        self._updateMethodInfo(note)

    def _onRowLevelChanged(self, combo):
        """Level typed in a row: also given to the other selected 'Manual level' rows."""
        row = self._rowOfWidget(combo, COL_METHOD)
        if row < 0:
            return
        self._markRowChanged(row)
        if self._propagating:
            return
        table = self.tablePolygons
        selected = self.selectedRows()
        others = [r for r in selected if r != row and self._rowMethod(r) == BaseLevelOptions.MANUAL_BASE_LEVEL] \
            if row in selected else []
        if others:
            level = table.cellWidget(row, COL_LEVEL).value()
            self._propagating = True
            try:
                for other in others:
                    table.cellWidget(other, COL_LEVEL).setValue(level)
                    self._markRowChanged(other)
            finally:
                self._propagating = False
        self._setCurrentRow(row)
        self._updateMethodInfo(_plural(len(others), tr("Level also applied to the other selected row (ID {})."),
                                       tr("Level also applied to the other selected rows (ID {}).")).format(
            self._rowIds(others)) if others else "")

    def _askLevel(self, rows):
        """Ask the manual base level for `rows`; None if cancelled."""
        table = self.tablePolygons
        levels = [table.cellWidget(r, COL_LEVEL).value() for r in rows]
        start = next((v for v in levels if v is not None), 0.0)
        if len(rows) == 1:
            label = tr("Base level of the polygon ({}):").format(self._unit_suffix)
        else:
            label = tr("Base level of the {} selected polygons ({}):").format(len(rows), self._unit_suffix)
        level, ok = QInputDialog.getDouble(
            self, tr("Manual level"), label, start, LEVEL_MIN + 1.0, 100000.0, 3)
        return level if ok else None

    def setRowsMethod(self, rows, method, level=None, ask_level=False, remember=True):
        """Give `method` (and, for 'Manual level', `level`) to the given rows.
        remember: the method becomes the default of the polygons without a stored method."""
        rows = list(rows)
        if not rows:
            return
        is_manual = method == BaseLevelOptions.MANUAL_BASE_LEVEL
        table = self.tablePolygons
        if is_manual and ask_level:
            level = self._askLevel(rows)
            if level is None:
                return
        for row in rows:
            combo = table.cellWidget(row, COL_METHOD)
            cell = table.cellWidget(row, COL_LEVEL)
            combo.blockSignals(True)  # avoid one full-table refresh per row
            combo.setCurrentIndex(max(0, combo.findData(method.code)))
            combo.blockSignals(False)
            cell.setManual(is_manual)
            if is_manual and level is not None:
                cell.spin.blockSignals(True)
                cell.setValue(level)
                cell.spin.blockSignals(False)
                cell._refreshStyle()
            self._markRowChanged(row)
        if remember:
            _store_setting("default_base_method", method.code)
        self._updateMethodInfo()
        self.updateBaseDemEnabled()

