    @staticmethod
    def _resultItem(text, tooltip="", error=None, volume_m3=None):
        item = QTableWidgetItem(text)
        item.setFlags(Qt.ItemFlag.ItemIsEnabled | Qt.ItemFlag.ItemIsSelectable)
        item.setTextAlignment(int(Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter))
        item.setToolTip(tooltip)
        item.setData(RESULT_M3_ROLE, volume_m3)
        item.setData(RESULT_ERROR_ROLE, error)
        if error:
            item.setForeground(QBrush(QColor(ERROR_COLOR)))
        return item

    def _rowError(self, row):
        for column in (COL_ABOVE, COL_BELOW):
            item = self.tablePolygons.item(row, column)
            if item is not None and item.data(RESULT_ERROR_ROLE):
                return item.data(RESULT_ERROR_ROLE)
        return None

    def _hasResults(self):
        table = self.tablePolygons
        return any(table.item(r, c) is not None and table.item(r, c).text()
                   for r in range(table.rowCount()) for c in (COL_ABOVE, COL_BELOW))

    def _resetProgress(self):
        """The '3/4 polygons computed' text no longer matches the table."""
        self.progressBar.setValue(0)
        self.progressBar.setFormat("")

    def setResults(self, results, counting, stored=False):
        """Show the volumes in the table, in the current output unit and decimals.

        results: {fid: {"above_m3": float, "below_m3": float, "tooltip": str, "error": str or None}}
        stored: the methods were written to the layer."""
        table = self.tablePolygons
        table.setColumnHidden(COL_ABOVE, not counting.writes_above)
        table.setColumnHidden(COL_BELOW, not counting.writes_below)
        # an error is written once, in the first visible result column
        error_column = COL_ABOVE if counting.writes_above else COL_BELOW
        table.blockSignals(True)
        for row in range(table.rowCount()):
            fid = table.item(row, COL_ID).data(Qt.ItemDataRole.UserRole)
            res = results.get(fid)
            if res is None:
                continue
            for column, key in ((COL_ABOVE, "above_m3"), (COL_BELOW, "below_m3")):
                if res.get("error"):
                    text = tr("Error") if column == error_column else "—"
                    item = self._resultItem(text, res["error"], error=res["error"])
                else:
                    item = self._resultItem("", res.get("tooltip", ""), volume_m3=float(res[key]))
                table.setItem(row, column, item)
            combo = table.cellWidget(row, COL_METHOD)
            if stored and combo is not None:
                combo.setProperty("origin", _tr_const(ORIGIN_STORED))
                combo.setToolTip(_tr_const(ORIGIN_STORED))
        table.blockSignals(False)
        self._refreshResultTexts()
        self._updateMethodInfo()

    def _refreshResultTexts(self):
        """Write the stored volumes (m3) in the current unit and decimals."""
        table = self.tablePolygons
        unit_key = self.selectedVolumeUnit()
        unit_label = VOLUME_UNITS[unit_key][0]
        decimals = self.outputAccuracy.value()
        locale = QLocale()
        table.horizontalHeaderItem(COL_ABOVE).setText(tr("Above ({})").format(unit_label))
        table.horizontalHeaderItem(COL_BELOW).setText(tr("Below ({})").format(unit_label))
        table.blockSignals(True)
        for row in range(table.rowCount()):
            for column in (COL_ABOVE, COL_BELOW):
                item = table.item(row, column)
                if item is None or item.data(RESULT_M3_ROLE) is None:
                    continue
                item.setText(locale.toString(convert_volume(float(item.data(RESULT_M3_ROLE)), unit_key),
                                             "f", decimals))
        table.blockSignals(False)

    def clearResults(self, rows=None):
        """Empty the result cells (all rows, or the given ones): they no longer match the inputs."""
        table = self.tablePolygons
        rows = range(table.rowCount()) if rows is None else rows
        cleared = False
        table.blockSignals(True)
        for row in rows:
            for column in (COL_ABOVE, COL_BELOW):
                item = table.item(row, column)
                if item is not None and item.text():
                    table.setItem(row, column, self._resultItem(""))
                    cleared = True
        table.blockSignals(False)
        if cleared:
            self._resetProgress()
            self._updateMethodInfo()

