def _looks_like_material(field_name):
    """'Matériau', 'materiaux', 'Material', 'MAT', 'mat_type'... (accents ignored)."""
    text = unicodedata.normalize("NFKD", field_name).encode("ascii", "ignore").decode().lower()
    return text.startswith("materi") or text == "mat" or text.startswith("mat_")


def _tr_const(text):
    """tr() of a module constant marked with tr_noop() (i18n_tool only accepts literal texts in tr())."""
    return tr(text)


def _plural(count, singular, plural):
    """`singular` or `plural` (two whole translated sentences) according to `count`, with the
    plural rule of the translation: English 1 -> singular, French 0 and 1 -> singular."""
    zero_is_singular = _tr_const(PLURAL_RULE).replace(" ", "") == "n>1"
    many = count > 1 if zero_is_singular else count != 1
    return plural if many else singular


class LevelCell(QStackedWidget):
    """'Manual level' cell: an editable spin box on 'Manual level' rows, a grey dash on the
    other rows (a disabled '0.000' was read as 'base at 0 m').

    A level that was never entered shows "enter level" in red and value() is None: the
    calculation refuses it instead of silently using a base at 0 m."""

    def __init__(self, value=None, parent=None):
        super().__init__(parent)
        self.dash = QLabel("—")
