    # ------------------------------------------------------------------ spline base of each polygon
    @staticmethod
    def splineDefaults():
        """(ring width, stiffness) of the polygons without their own: the last ones chosen."""
        return (_setting("spline_ring_width", DEFAULT_RING_WIDTH, float),
                _setting("spline_stiffness", DEFAULT_SPLINE_STIFFNESS, float))

    def splineParams(self, fid):
        return self._splineParams.get(fid) or self.splineDefaults()

    def setSplineParams(self, fid, ring_width, stiffness, remember=True):
        """Spline base of polygon `fid`; remember: also the default of the polygons without one."""
        self._splineParams[fid] = (float(ring_width), float(stiffness))
        if remember:
            _store_setting("spline_ring_width", float(ring_width))
            _store_setting("spline_stiffness", float(stiffness))
        row = self.rowOfFid(fid)
        if row >= 0 and self._rowMethod(row) == BaseLevelOptions.SPLINE_RING:
            self.clearResults([row])

    # ------------------------------------------------------------------ polygon table
    def populatePolygonTable(self, layer_id, rows):
        """rows: list of dicts with keys fid, name, method (BaseLevelOptions or None), level (float or None).
        Choices already made in the table for the same layer are kept (not the volumes: the
        polygons may have been edited, which is why the table is reloaded)."""
        previous = {}
        if layer_id is not None and layer_id == self._table_layer_id:
            previous = {c["fid"]: c for c in self.polygonChoices(only_included=False)}
        else:
            self._splineParams = {}
        self._table_layer_id = layer_id
        # spline base stored in the layer (Base_ring / Base_stiff), unless already set in this dialog
        default_ring, default_stiffness = self.splineDefaults()
        for data in rows:
            ring, stiffness = data.get("ring"), data.get("stiffness")
            if data["fid"] not in self._splineParams and (ring is not None or stiffness is not None):
                self._splineParams[data["fid"]] = (default_ring if ring is None else float(ring),
                                                   default_stiffness if stiffness is None else float(stiffness))
        if self._hasResults():
            self._resetProgress()

        default_method = self.defaultBaseMethod()
        table = self.tablePolygons
        table.setUpdatesEnabled(False)
        table.blockSignals(True)  # no itemChanged refresh per created row
        table.setRowCount(0)
        table.setRowCount(len(rows))
        for row, data in enumerate(rows):
            fid = data["fid"]
            prev = previous.get(fid)
            if prev:
                method, origin, level = prev["method"], prev["origin"], prev["level"]
            elif data.get("method") is not None:
                method, origin, level = data["method"], _tr_const(ORIGIN_STORED), data.get("level")
            else:
                method, origin, level = default_method, _tr_const(ORIGIN_DEFAULT).format(default_method.short_label), None
            included = prev["include"] if prev else True

            use_item = QTableWidgetItem()
            use_item.setFlags(Qt.ItemFlag.ItemIsEnabled | Qt.ItemFlag.ItemIsUserCheckable | Qt.ItemFlag.ItemIsSelectable)
            use_item.setCheckState(Qt.CheckState.Checked if included else Qt.CheckState.Unchecked)
            table.setItem(row, COL_USE, use_item)

            id_item = QTableWidgetItem(str(fid))
            id_item.setData(Qt.ItemDataRole.UserRole, fid)
            id_item.setToolTip(tr("Double-click to zoom the map on this polygon"))
            table.setItem(row, COL_ID, id_item)
            name_item = QTableWidgetItem(str(data.get("name") or ""))
            name_item.setToolTip(tr("Double-click to zoom the map on this polygon"))
            table.setItem(row, COL_NAME, name_item)

            combo = QComboBox()
            for option in BASE_LEVEL_ORDER:
                combo.addItem(option.short_label, option.code)
                combo.setItemData(combo.count() - 1, option.explanation, Qt.ItemDataRole.ToolTipRole)
            combo.setCurrentIndex(max(0, combo.findData(method.code)))
            combo.setProperty("origin", origin)
            combo.setToolTip(origin)
            table.setCellWidget(row, COL_METHOD, combo)

            cell = LevelCell(level)
            cell.setSuffix(" " + self._unit_suffix)
            cell.setManual(method == BaseLevelOptions.MANUAL_BASE_LEVEL)
            table.setCellWidget(row, COL_LEVEL, cell)
            # currentIndexChanged: any change (code or user) -> row state.
            # activated: a choice made by the user -> selection propagation and level prompt.
            combo.currentIndexChanged.connect(self._ifShown(lambda _i, c=combo: self._onRowMethodChanged(c)))
            combo.activated.connect(self._ifShown(lambda _i, c=combo: self._onRowMethodActivated(c)))
            cell.spin.valueChanged.connect(self._ifShown(lambda _v, c=combo: self._onRowLevelChanged(c)))
            for column in (COL_ABOVE, COL_BELOW):
                table.setItem(row, column, self._resultItem(""))
        table.blockSignals(False)
        table.setUpdatesEnabled(True)
        self._onTableChanged()

    def _rowOfWidget(self, widget, column):
        table = self.tablePolygons
        for row in range(table.rowCount()):
            if table.cellWidget(row, column) is widget:
                return row
        return -1

    def _rowMethod(self, row):
        return BaseLevelOptions.from_code(self.tablePolygons.cellWidget(row, COL_METHOD).currentData())

    def _rowIds(self, rows):
        return ", ".join(self.tablePolygons.item(r, COL_ID).text() for r in rows)

