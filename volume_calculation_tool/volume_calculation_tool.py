    def buildBasePreview(self, fid, computer_class):
        dlg = self.dlg
        height_layer = dlg.mFieldComboHeightLayer.currentLayer()
        vector_layer = dlg.mFieldComboPolygon.currentLayer()
        if isinstance(height_layer, QgsPointCloudLayer):
            raise UserInputError(tr("The 3D view needs a DEM raster: with a point cloud, check 'Keep the DEM of "
                                    "the whole cloud', compute, then select that DEM."))
        if vector_layer is None or not isinstance(height_layer, QgsRasterLayer) or not height_layer.isValid():
            raise UserInputError(tr("Select a polygon layer and a valid DEM height layer."))
        band = dlg.mFieldComboBand.currentBand()
        dem_crs = height_layer.crs()
        if band < 1 or not dem_crs.isValid() or dem_crs.isGeographic():
            raise UserInputError(tr("The DEM height layer needs a band and a projected CRS (metres or feet)."))
        linear_factor = crs_linear_factor_to_meters(dem_crs)
        if linear_factor is None:
            raise UserInputError(tr("The map unit of the DEM CRS ({}) is not supported.").format(dem_crs.authid()))

        pixel_x = abs(height_layer.rasterUnitsPerPixelX())
        pixel_y = abs(height_layer.rasterUnitsPerPixelY())
        step_x = dlg.doubleSpinBoxSampleStepX.value()
        step_y = dlg.doubleSpinBoxSampleStepY.value()
        half_unit = 0.5 * 10 ** -dlg.doubleSpinBoxSampleStepX.decimals() + 1e-12
        if abs(step_x - pixel_x) <= half_unit:
            step_x = pixel_x
        if abs(step_y - pixel_y) <= half_unit:
            step_y = pixel_y

        # base DEM (only used by the 'Base DEM' method; without it that method shows its error)
        # A layer that cannot be used (web tiles, geographic CRS...) only blocks that method, not the view.
        base_provider, base_band, base_crs_wkts = None, 1, None
        base_problem = tr("No base DEM layer selected.")
        base_layer = dlg.mFieldComboHeightLayerBase.currentLayer()
        if base_layer is not None:
            provider = base_layer.dataProvider() if base_layer.isValid() else None
            if provider is None or provider.xSize() <= 0 or provider.ySize() <= 0:
                base_problem = tr("'{}' is not a DEM with a pixel grid (web tiles?): select an elevation "
                                  "raster.").format(base_layer.name())
            elif dlg.mFieldComboBandBase.currentBand() < 1:
                base_problem = tr("Select a band of the base DEM layer.")
            elif not base_layer.crs().isValid() or base_layer.crs().isGeographic():
                base_problem = tr("The base DEM layer needs a projected CRS (metres or feet).")
            else:
                base_problem = None
                base_band = dlg.mFieldComboBandBase.currentBand()
                if base_layer.crs() != dem_crs:
                    base_crs_wkts = (crs_to_gdal_wkt(dem_crs), crs_to_gdal_wkt(base_layer.crs()))
                base_provider = provider.clone()

        # this polygon and the checked ones (excluded from the spline ground ring), in the DEM CRS
        transform = None
        if vector_layer.crs().isValid() and vector_layer.crs() != dem_crs:
            transform = QgsCoordinateTransform(vector_layer.crs(), dem_crs, QgsProject.instance())
        choices = {c["fid"]: c for c in dlg.polygonChoices(only_included=False)}
        if fid not in choices:
            raise UserInputError(tr("This polygon is no longer in the table (press 'Reload')."))
        wanted = {fid} | {f for f, c in choices.items() if c["include"]}
        geometries = {}
        for feature in vector_layer.getFeatures(QgsFeatureRequest().setFilterFids(list(wanted))):
            geom = feature.geometry()
            if geom is None or geom.isEmpty():
                continue
            if transform is not None:
                geom.transform(transform)
            if not geom.isGeosValid():
                fixed = geom.makeValid()
                if fixed is not None and not fixed.isEmpty():
                    geom = fixed
            geometries[feature.id()] = geom
        if fid not in geometries:
            raise UserInputError(tr("Polygon {} has no geometry.").format(fid))
        all_polygons = QgsGeometry.unaryUnion(list(geometries.values()))

        settings = CalculationSettings(
            height_layer.dataProvider().clone(), band,
            height_layer.extent().xMinimum(), height_layer.extent().yMaximum(), pixel_x, pixel_y,
            step_x, step_y, linear_factor,
            base_provider=base_provider, base_band=base_band, base_crs_wkts=base_crs_wkts,
            ring_width=choices[fid]["ring"])
        choice = choices[fid]
        computer = computer_class(fid, choice["name"], geometries[fid], settings, all_polygons,
                                  lambda: self.dlg.rowManualLevel(fid) if self.dlg is not None else None,
                                  base_problem=base_problem,
                                  spline_params=(choice["ring"], choice["stiffness"]))
        if choice["name"]:
            title = tr("3D view – ID {} – {}").format(fid, choice["name"])
        else:
            title = tr("3D view – ID {}").format(fid)
        return computer, choice["method"], title

    # ------------------------------------------------------------------ workflow
    def workflow(self):
        if self.task is not None:
            return
        self._cancel_requested = False
        layer = self.dlg.mFieldComboHeightLayer.currentLayer()
        if isinstance(layer, QgsPointCloudLayer):
            self.startPointCloudConversion(layer)
        else:
            self.startVolumeCalculation()

    # ---- step 1 (point clouds only): triangulate the points into a DEM ---------
    def startPointCloudConversion(self, cloud):
        dlg = self.dlg
        try:
            plan = self.buildPointCloudConversion(cloud)
        except UserInputError as exc:
            dlg.popWarningBox(str(exc))
            return
        except Exception as exc:
            QgsMessageLog.logMessage(traceback.format_exc(), MESSAGE_CATEGORY, Qgis.Critical)
            dlg.popFatalErrorBox(tr("Unexpected error while preparing the point cloud: {}").format(exc))
            return
        if plan is None:
            return
        if plan["reuse"]:
            self.appendLogLine(tr("DEM of point cloud '{}' reused: {}")
                               .format(cloud.name(), plan["output"]))
            self.onPointCloudDemReady(cloud, plan)
            return
        algorithm = QgsApplication.processingRegistry().algorithmById(PDAL_TIN_ALGORITHM)
        context = QgsProcessingContext()
        context.setProject(QgsProject.instance())
        feedback = QgsProcessingFeedback()
        task = QgsProcessingAlgRunnerTask(algorithm, plan["params"], context, feedback)
        note = plan["note"]
        # keep Python references alive while the task runs
        self._conversion = {"context": context, "feedback": feedback, "cloud": cloud, "plan": plan,
                            "output": plan["output"], "note": note, "task": task}
        task.executed.connect(self.onPointCloudConverted)
        task.progressChanged.connect(self.updateProgressBar)
        self.task = task
        self.appendLogLine(tr("DEM from point cloud '{}' ({})…").format(cloud.name(), note))
        dlg.progressBar.setValue(0)
        dlg.lockupGUIDuringCalculation()
        QgsApplication.taskManager().addTask(task)

    def buildPointCloudConversion(self, cloud):
        """Plan of the triangulation: dict(params, output, note, keep, reuse) or None (aborted).

        keep=False: DEM restricted to the included polygons (+ margin), temporary file.
        keep=True : DEM of the whole point cloud saved next to the LAS file, shown as a
                    hillshade in the project, and reused as long as the LAS file is unchanged."""
        dlg = self.dlg
        if not cloud.isValid():
            raise UserInputError(tr("The point cloud layer is not valid."))
        if QgsApplication.processingRegistry().algorithmById(PDAL_TIN_ALGORITHM) is None:
            raise UserInputError(tr("The PDAL processing tools are not available: QGIS 3.32 or newer is required "
                                    "to use point clouds (or convert the points to a DEM raster first)."))
        crs = cloud.crs()
        if not crs.isValid():
            raise UserInputError(tr("The point cloud has no coordinate reference system: set it in the layer "
                                    "properties."))
        if crs.isGeographic():
            raise UserInputError(tr("The point cloud uses a geographic CRS ({}): a projected CRS in metres or feet "
                                    "is needed.").format(crs.authid()))
        vector_layer = dlg.mFieldComboPolygon.currentLayer()
        if vector_layer is None:
            raise UserInputError(tr("Select a polygon layer."))
        choices = dlg.polygonChoices(only_included=True)
        if not choices:
            raise UserInputError(tr("No polygon is checked in the table ('Compute' column)."))
        check_manual_levels(choices)
        resolution = dlg.doubleSpinBoxCloudResolution.value()

        # extent of the included polygons, in the point cloud CRS, with a margin
        transform = None
        if vector_layer.crs().isValid() and vector_layer.crs() != crs:
            transform = QgsCoordinateTransform(vector_layer.crs(), crs, QgsProject.instance())
        extent = None
        request = QgsFeatureRequest().setFilterFids([c["fid"] for c in choices])
        for feature in vector_layer.getFeatures(request):
            geom = feature.geometry()
            if geom is None or geom.isEmpty():
                continue
            if transform is not None:
                geom.transform(transform)
            if extent is None:
                extent = QgsRectangle(geom.boundingBox())
            else:
                extent.combineExtentWith(geom.boundingBox())
        if extent is None or not extent.intersects(cloud.extent()):
            raise UserInputError(tr("The included polygons do not overlap the point cloud extent."))
        margin = max(1.0, 5.0 * resolution)
        extent = QgsRectangle(extent.xMinimum() - margin, extent.yMinimum() - margin,
                              extent.xMaximum() + margin, extent.yMaximum() + margin)

        ground_only = dlg.checkBoxGroundOnly.isChecked()
        las_path = layer_file_path(cloud)
        keep = dlg.checkBoxLoadCloudDem.isChecked() and bool(las_path) and os.path.exists(las_path)
        # description of the DEM (log): one whole text per case, for the translations
        if keep and ground_only:
            note = tr("TIN, resolution {:g} {}, ground class only, whole point cloud")
        elif keep:
            note = tr("TIN, resolution {:g} {}, all points, whole point cloud")
        elif ground_only:
            note = tr("TIN, resolution {:g} {}, ground class only, polygons area only")
        else:
            note = tr("TIN, resolution {:g} {}, all points, polygons area only")
        note = note.format(resolution, crs_unit_abbreviation(crs))
        filters = [GROUND_CLASS_FILTER] if ground_only else []
        reuse = False
        if keep:
            # whole point cloud: the DEM is also a map layer (hillshade for the layouts)
            output_path = "{}_DEM_TIN_{}{}.tif".format(os.path.splitext(las_path)[0],
                                                     ("%g" % resolution).replace(".", "p"),
                                                     "_class2" if ground_only else "")
            reuse = (os.path.exists(output_path)
                     and os.path.getmtime(output_path) >= os.path.getmtime(las_path)
                     and QgsRasterLayer(output_path, "check").isValid())
            if not reuse and not self.prepareOutputPath(output_path, "dem"):
                return None
        else:
            output_path = os.path.join(QgsProcessingUtils.tempFolder(),
                                       "volume_tin_{}.tif".format(datetime.now().strftime("%Y%m%d_%H%M%S_%f")))
            # The area is cropped with an X/Y expression written at full precision, NOT with
            # FILTER_EXTENT: QGIS (3.44) passes that extent to pdal_wrench with 6 significant
            # digits only (5000008.75 -> "5.00001e+06"), i.e. up to ~10 m off in UTM / Lambert-93.
            filters += ["X >= {:.3f}".format(extent.xMinimum()), "X <= {:.3f}".format(extent.xMaximum()),
                        "Y >= {:.3f}".format(extent.yMinimum()), "Y <= {:.3f}".format(extent.yMaximum())]
        params = {
            "INPUT": cloud,
            "RESOLUTION": resolution,
            "TILE_SIZE": 1000,
            "FILTER_EXPRESSION": " AND ".join(filters),
            "OUTPUT": output_path,
        }
        return {"params": params, "output": output_path, "note": note, "keep": keep, "reuse": reuse}

    def onPointCloudConverted(self, success, results):
        conversion = getattr(self, "_conversion", None) or {}
        self._conversion = None
        self.task = None
        if self.dlg is None:
            return
        try:
            self.dlg.unlockGUI()
            feedback = conversion.get("feedback")
            output = (results or {}).get("OUTPUT") or conversion.get("output")
            if not success:
                if self.cancel_requested_flag():
                    self.appendLogLine(tr("Cancelled: nothing written."))
                    self.dlg.progressBar.setValue(0)
                    return
                details = feedback.textLog().strip().splitlines()[-8:] if feedback is not None else []
                hint = ""
                if self.dlg.checkBoxGroundOnly.isChecked():
                    hint = "\n\n" + tr("Unclassified ground points? Uncheck 'Ground class only'.")
                self.dlg.popFatalErrorBox(tr("The point cloud could not be interpolated into a DEM.") + "\n\n"
                                          + "\n".join(details) + hint)
                self.dlg.progressBar.setValue(0)
                return
            plan = dict(conversion["plan"], output=output)
            self.appendLogLine(tr("DEM written: {}").format(output))
            self.onPointCloudDemReady(conversion["cloud"], plan)
        except Exception:
            trace = traceback.format_exc()
            QgsMessageLog.logMessage(trace, MESSAGE_CATEGORY, Qgis.Critical)
            self.dlg.unlockGUI()
            self.dlg.popFatalErrorBox(tr("Unexpected error after the point cloud interpolation:\n{}")
                                      .format(trace.splitlines()[-1]))

    def onPointCloudDemReady(self, cloud, plan):
        """DEM available (new or reused): show it in the project if kept, then compute."""
        output = plan["output"]
        dem = None
        if plan["keep"]:
            target = normalized_path(output)
            for layer in QgsProject.instance().mapLayers().values():
                if isinstance(layer, QgsRasterLayer) and normalized_path(layer_file_path(layer) or "?") == target:
                    dem = layer   # already in the project (maybe in a layout): leave it untouched
                    break
            if dem is None:
                dem = QgsRasterLayer(output, tr("{} DEM (TIN)").format(cloud.name()))
                if dem.isValid():
                    self.applyHillshadeStyle(dem, os.path.splitext(output)[0] + ".qml")
                    QgsProject.instance().addMapLayer(dem)
        if dem is None:
            dem = QgsRasterLayer(output, tr("{} DEM (TIN)").format(cloud.name()))
        if not dem.isValid():
            self.dlg.popFatalErrorBox(tr("The interpolated DEM could not be read: {}").format(output))
            return
        self.startVolumeCalculation(height_layer=dem, source_layer=cloud,
                                    source_note=tr("point cloud '{}' ({})").format(cloud.name(), plan["note"]))

    @staticmethod
    def applyHillshadeStyle(layer, qml_path=None):
        """Multidirectional hillshade, ready for print layouts. The style is also saved as a
        .qml next to the DEM, so QGIS applies it again when the file is opened elsewhere."""
        renderer = QgsHillshadeRenderer(layer.dataProvider(), 1, 315.0, 45.0)
        renderer.setMultiDirectional(True)
        renderer.setZFactor(1.0)
        layer.setRenderer(renderer)
        layer.triggerRepaint()
        if qml_path:
            try:
                layer.saveNamedStyle(qml_path)
            except Exception:
                pass

    def cancel_requested_flag(self):
        flag = getattr(self, "_cancel_requested", False)
        self._cancel_requested = False
        return flag

    # ---- step 2: volume calculation on a DEM --------------------------------------
    def startVolumeCalculation(self, height_layer=None, source_layer=None, source_note=None):
        try:
            built = self.buildCalculation(height_layer, source_layer, source_note)
        except UserInputError as exc:
            self.dlg.popWarningBox(str(exc))
            return
        except Exception as exc:
            QgsMessageLog.logMessage(repr(exc), MESSAGE_CATEGORY, Qgis.Critical)
            self.dlg.popFatalErrorBox(tr("Unexpected error while preparing the calculation: {}").format(exc))
            return
        if built is None:
            return
        jobs, settings, ctx = built
        self.run_ctx = ctx
        task = AccurateVolumeCalculationTask(tr(ACCURATE_WORKFLOW_DESCRIPTION), jobs, settings, self.onTaskFinished)
        task.progressChanged.connect(self.updateProgressBar)
        self.task = task
        self.dlg.progressBar.setValue(0)
        self.dlg.lockupGUIDuringCalculation()
        QgsApplication.taskManager().addTask(task)

    def cancelLongWorkflow(self):
        if self.task is not None:
            self._cancel_requested = True
            try:
                self.task.cancel()
            except RuntimeError:
                self.task = None
                self.dlg.unlockGUI()

    def updateProgressBar(self, progress):
        if self.dlg is not None and progress >= 0:
            self.dlg.progressBar.setValue(int(round(min(max(progress, 0.0), 100.0))))

    def buildCalculation(self, height_layer=None, source_layer=None, source_note=None):
        """Validate the inputs and build (jobs, settings, ctx). Returns None if the user aborted.

        height_layer: DEM to use instead of the selected layer (DEM interpolated from a point cloud)
        source_layer: layer the DEM comes from (used for the log and the nDOM file name)
        """
        dlg = self.dlg
        derived_dem = height_layer is not None
        if height_layer is None:
            height_layer = dlg.mFieldComboHeightLayer.currentLayer()
        source_layer = source_layer or height_layer
        vector_layer = dlg.mFieldComboPolygon.currentLayer()
        if height_layer is None or vector_layer is None:
            raise UserInputError(tr("Select a polygon layer and a DEM height layer."))
        if not isinstance(height_layer, QgsRasterLayer) or not height_layer.isValid():
            raise UserInputError(tr("The DEM height layer is not valid."))
        height_band = 1 if derived_dem else dlg.mFieldComboBand.currentBand()
        if height_band < 1:
            raise UserInputError(tr("Select a band of the DEM height layer."))

        dem_crs = height_layer.crs()
        if not dem_crs.isValid():
            raise UserInputError(tr("The DEM height layer has no coordinate reference system."))
        if dem_crs.isGeographic():
            raise UserInputError(tr("The DEM uses a geographic CRS ({}): reproject it to a projected CRS "
                                    "(metres or feet).").format(dem_crs.authid()))
        linear_factor = crs_linear_factor_to_meters(dem_crs)
        if linear_factor is None:
            raise UserInputError(tr("The map unit of the DEM CRS ({}) is not a supported distance unit.")
                                 .format(dem_crs.authid()))

        step_x = dlg.doubleSpinBoxSampleStepX.value()
        step_y = dlg.doubleSpinBoxSampleStepY.value()
        if step_x <= 0 or step_y <= 0:
            raise UserInputError(tr("The sampling step sizes must be greater than 0."))
        # The spin boxes round the DEM pixel size to their decimals (0.04987 -> 0.0499): a step
        # equal to the rounded pixel size means "one sample per pixel", i.e. the exact DEM grid.
        pixel_x = abs(height_layer.rasterUnitsPerPixelX())
        pixel_y = abs(height_layer.rasterUnitsPerPixelY())
        half_unit = 0.5 * 10 ** -dlg.doubleSpinBoxSampleStepX.decimals() + 1e-12
        if abs(step_x - pixel_x) <= half_unit:
            step_x = pixel_x
        if abs(step_y - pixel_y) <= half_unit:
            step_y = pixel_y

        choices = dlg.polygonChoices(only_included=True)
        if not choices:
            raise UserInputError(tr("No polygon is checked in the table ('Compute' column)."))
        check_manual_levels(choices)
        counting = dlg.selectedCountingOption()
        name_pos, name_neg = dlg.getFieldNames()
        add_field = dlg.checkBox_add_field.isChecked()
        warnings = []

        # ---- output field checks (before computing anything) -------------------
        if add_field:
            if counting == CountOptions.COUNT_ABOVE_AND_BELOW and name_pos.lower() == name_neg.lower():
                raise UserInputError(tr("The 'Above' and 'Below' field names must be different."))
            reserved = {name.lower() for name in METHOD_FIELDS}
            if name_pos.lower() in reserved or name_neg.lower() in reserved:
                raise UserInputError(tr("{} are reserved field names.").format(", ".join(METHOD_FIELDS)))
            if not vector_layer.isEditable():
                provider = vector_layer.dataProvider()
                if not provider_has_capability(provider, "ChangeAttributeValues"):
                    raise UserInputError(tr("Layer '{}' is read-only: uncheck 'Write the volumes to the layer'.")
                                         .format(vector_layer.name()))
                if not provider_has_capability(provider, "AddAttributes"):
                    names = [name_pos, name_neg, BASE_METHOD_FIELD, BASE_LEVEL_FIELD]
                    if any(c["method"] == BaseLevelOptions.SPLINE_RING for c in choices):
                        names += [BASE_RING_FIELD, BASE_STIFF_FIELD]
                    if any(vector_layer.fields().lookupField(n) == -1 for n in names):
                        raise UserInputError(tr("Fields cannot be added to layer '{}'.").format(vector_layer.name()))

        # ---- base DEM --------------------------------------------------------------
        uses_dem = any(c["method"] == BaseLevelOptions.USE_DEM_LAYER for c in choices)
        base_provider = None
        base_band = 1
        base_crs_wkts = None
        base_layer = None
        if uses_dem:
            base_layer = dlg.mFieldComboHeightLayerBase.currentLayer()
            if base_layer is None or not base_layer.isValid():
                raise UserInputError(tr("Select a valid base DEM layer (method “{}”).")
                                     .format(BaseLevelOptions.USE_DEM_LAYER.short_label))
            if base_layer.dataProvider().xSize() <= 0 or base_layer.dataProvider().ySize() <= 0:
                raise UserInputError(tr("'{}' is not a DEM with a pixel grid (web tiles?): select an elevation "
                                        "raster.").format(base_layer.name()))
            base_band = dlg.mFieldComboBandBase.currentBand()
            if base_band < 1:
                raise UserInputError(tr("Select a band of the DEM base layer."))
            base_crs = base_layer.crs()
            if not base_crs.isValid():
                warnings.append(tr("The base DEM has no CRS: assumed identical to the height DEM CRS."))
            elif base_crs != dem_crs:
                if base_crs.isGeographic():
                    raise UserInputError(tr("The base DEM uses a geographic CRS ({}): reproject it first.")
                                         .format(base_crs.authid()))
                base_crs_wkts = (crs_to_gdal_wkt(dem_crs), crs_to_gdal_wkt(base_crs))
                warnings.append(tr("Base DEM ({}) reprojected on the fly to the DEM CRS ({}).")
                                .format(base_crs.authid(), dem_crs.authid()))
            base_provider = base_layer.dataProvider().clone()

        # ---- polygons, in the DEM CRS ---------------------------------------------
        vector_crs = vector_layer.crs()
        transform = None
        if not vector_crs.isValid():
            warnings.append(tr("The polygon layer has no CRS: assumed identical to the DEM CRS."))
        elif vector_crs != dem_crs:
            transform = QgsCoordinateTransform(vector_crs, dem_crs, QgsProject.instance())
            warnings.append(tr("Polygons ({}) are reprojected to the DEM CRS ({}).")
                            .format(vector_crs.authid(), dem_crs.authid()))

        by_fid = {c["fid"]: c for c in choices}
        features = {f.id(): f for f in vector_layer.getFeatures(QgsFeatureRequest().setFilterFids(list(by_fid)))}
        jobs = []
        for fid, choice in by_fid.items():
            feature = features.get(fid)
            if feature is None:
                warnings.append(tr("Feature {} no longer exists in the layer (press 'Reload').").format(fid))
                continue
            geom = feature.geometry()
            if geom is None or geom.isEmpty():
                warnings.append(tr("Feature {} has no geometry, skipped.").format(fid))
                continue
            if transform is not None:
                try:
                    geom.transform(transform)
                except QgsCsException as exc:
                    warnings.append(tr("Feature {} could not be reprojected ({}), skipped.").format(fid, exc))
                    continue
            if not geom.isGeosValid():
                fixed = geom.makeValid()
                if fixed is not None and not fixed.isEmpty():
                    geom = fixed
                    warnings.append(tr("Feature {} had an invalid geometry, it was repaired for the calculation.")
                                    .format(fid))
            level = choice["level"] if choice["level"] is not None else 0.0   # unused unless 'Manual level'
            jobs.append(PolygonJob(fid, choice["name"], geom, choice["method"], level,
                                   ring_width=choice["ring"], stiffness=choice["stiffness"]))
        if not jobs:
            raise UserInputError(tr("None of the included polygons can be computed:\n{}").format("\n".join(warnings)))

        # ---- raster grid -------------------------------------------------------------
        extent = height_layer.extent()
        total_cells = estimate_cell_count([j.geometry for j in jobs], extent.xMinimum(), extent.yMaximum(), step_x, step_y)
        if total_cells > LARGE_JOB_CELLS:
            if not dlg.askOkCancel(tr("Large calculation"),
                                   tr("About {:.0f} million cells to sample: this can take a while (a larger "
                                      "step is faster).\n\nContinue?")
                                   .format(total_cells / 1e6)):
                return None

        # ---- nDOM output -------------------------------------------------------------
        ndom_path = None
        if dlg.checkBox_create_ndom.isChecked():
            ndom_path = self.getNDOMOutputPath(source_layer)
            if not self.prepareOutputPath(ndom_path, "ndom"):
                return None

        settings = CalculationSettings(
            height_layer.dataProvider().clone(), height_band,
            extent.xMinimum(), extent.yMaximum(), pixel_x, pixel_y,
            step_x, step_y, linear_factor,
            base_provider=base_provider, base_band=base_band, base_crs_wkts=base_crs_wkts,
            ndom_path=ndom_path, ndom_crs_wkt=crs_to_gdal_wkt(dem_crs) if ndom_path else "",
            ring_width=dlg.splineDefaults()[0])   # spline ring / stiffness: given per polygon (jobs)
        notes = []

        ctx = {
            "vector_layer": vector_layer,
            "height_layer": source_layer,
            "height_note": source_note,
            "base_layer": base_layer,
            "counting": counting,
            "name_pos": name_pos,
            "name_neg": name_neg,
            "add_field": add_field,
            "labels": add_field and dlg.checkBox_labels.isChecked(),
            "label_name_field": dlg.labelNameField(),
            "unit_key": dlg.selectedVolumeUnit(),
            "decimals": dlg.outputAccuracy.value(),
            "dem_unit": crs_unit_abbreviation(dem_crs),
            "step_x": step_x,
            "step_y": step_y,
            "pixel_x": pixel_x,
            "pixel_y": pixel_y,
            "ndom_path": ndom_path,
            "warnings": warnings,
            "notes": notes,
            "jobs": jobs,
        }
        return jobs, settings, ctx

    # ------------------------------------------------------------------ results
    def onTaskFinished(self, task, success):
        # Called from QgsTask.finished() (C++ virtual): an uncaught Python exception here
        # would take QGIS down, so everything is guarded.
        self.task = None
        try:
            self._handleTaskResult(task, success)
        except Exception:
            trace = traceback.format_exc()
            QgsMessageLog.logMessage(trace, MESSAGE_CATEGORY, Qgis.Critical)
            if self.dlg is not None:
                self.dlg.unlockGUI()
                self.dlg.popFatalErrorBox(tr("Unexpected error while writing the results:\n{}")
                                          .format(trace.splitlines()[-1]))

    def _handleTaskResult(self, task, success):
        ctx = self.run_ctx
        if self.dlg is None or ctx is None:
            return
        self.dlg.unlockGUI()

        if not success:
            self.removeFile(ctx["ndom_path"])
            self.dlg.progressBar.setValue(0)
            if task.exception is not None:
                self.dlg.popFatalErrorBox(tr("The calculation failed: {}\n\nDetails are in the Log Messages panel "
                                             "(tab '{}').").format(task.exception, MESSAGE_CATEGORY))
            else:
                self.appendLogLine(tr("Cancelled: nothing written."))
            return

        results = task.results
        self.updateOutputLog(results, ctx, task)

        stored = False
        write_error = None
        if ctx["add_field"]:
            try:
                self.writeResultsToLayer(results, ctx)
                stored = True
                if ctx["labels"]:
                    self.applyVolumeLabels(ctx)
            except Exception as exc:
                write_error = exc
        # the methods are marked "stored in the layer" only once they really are
        self.showResultsInTable(results, ctx, stored)
        if write_error is not None:
            self.dlg.popFatalErrorBox(tr("The volumes could not be written to layer '{}': {}")
                                      .format(ctx["vector_layer"].name(), write_error))

        if ctx["ndom_path"] and task.ndom_written:
            self.loadNDOM(ctx["ndom_path"], task.ndom_abs_max)

        failed = [r for r in results.values() if not r.ok]
        self.dlg.progressBar.setValue(100)
        self.dlg.progressBar.setFormat(tr("{}/{} computed").format(len(ctx["jobs"]) - len(failed),
                                                                  len(ctx["jobs"])))
        if len(failed) == 1:
            self.dlg.popWarningBox(tr("1 polygon not computed: see the log."))
        elif failed:
            self.dlg.popWarningBox(tr("{} polygons not computed: see the log.").format(len(failed)))

    def showResultsInTable(self, results, ctx, stored=False):
        """Above / below volumes of each polygon in the table (tooltip: base and warnings)."""
        rows = {}
        for job in ctx["jobs"]:
            res = results.get(job.fid) or PolygonResult(job.fid, job.name, job.method)
            if not res.ok:
                rows[job.fid] = {"error": res.error or tr("not computed")}
                continue
            tips = [tr("Base: {} - {}").format(job.method.short_label, res.base_description(ctx["dem_unit"]))]
            if res.cells_inside and res.coverage < COVERAGE_WARNING_THRESHOLD:
                tips.append(tr("Warning: only {:.1f} % of the polygon has DEM data.").format(res.coverage * 100.0))
            tips += res.notes
            rows[job.fid] = {"above_m3": res.above_m3, "below_m3": res.below_m3,
                             "tooltip": "\n".join(tips), "error": None}
        self.dlg.setResults(rows, ctx["counting"], stored=stored)

    def _result_values(self, res, ctx):
        """Values written for one polygon, in the output unit and rounded."""
        unit_key = ctx["unit_key"]
        decimals = ctx["decimals"]
        if not res.ok:
            return NULL, NULL
        above = round(convert_volume(res.above_m3, unit_key), decimals)
        below = round(convert_volume(res.below_m3, unit_key), decimals)
        return above, below

    def writeResultsToLayer(self, results, ctx):
        layer = ctx["vector_layer"]
        counting = ctx["counting"]
        wanted = []
        if counting.writes_above:
            wanted.append((ctx["name_pos"], "double"))
        if counting.writes_below:
            wanted.append((ctx["name_neg"], "double"))
        wanted += [(BASE_METHOD_FIELD, "string"), (BASE_LEVEL_FIELD, "double")]
        if any(res.method == BaseLevelOptions.SPLINE_RING for res in results.values()):
            wanted += [(BASE_RING_FIELD, "double"), (BASE_STIFF_FIELD, "double")]

        editing = layer.isEditable()
        provider = layer.dataProvider()
        index = self._addMissingFields(layer, wanted)

        changes = {}
        for fid, res in results.items():
            above, below = self._result_values(res, ctx)
            values = {index[BASE_METHOD_FIELD]: res.method.code}
            if res.method == BaseLevelOptions.MANUAL_BASE_LEVEL:
                values[index[BASE_LEVEL_FIELD]] = res.base_z
            elif res.ok and res.base_z is not None:
                values[index[BASE_LEVEL_FIELD]] = round(res.base_z, 3)
            else:
                values[index[BASE_LEVEL_FIELD]] = NULL
            if res.method == BaseLevelOptions.SPLINE_RING and res.ring_width is not None:
                # other methods keep the stored spline settings (back to the spline later)
                values[index[BASE_RING_FIELD]] = res.ring_width
                values[index[BASE_STIFF_FIELD]] = res.stiffness
            if counting.writes_above:
                values[index[ctx["name_pos"]]] = above
            if counting.writes_below:
                values[index[ctx["name_neg"]]] = below
            changes[fid] = values

        if editing:
            for fid, values in changes.items():
                for field_index, value in values.items():
                    layer.changeAttributeValue(fid, field_index, value)
            self.appendLogLine(tr("Layer '{}' is in edit mode: save the edits to keep the volumes.").format(layer.name()))
        else:
            if not provider.changeAttributeValues(changes):
                raise RuntimeError(", ".join(provider.errors()) or tr("provider error"))
            layer.reload()
        layer.triggerRepaint()

    @staticmethod
    def _addMissingFields(layer, wanted):
        """Add the fields of `wanted` [(name, kind)] the layer does not have; {name: index}."""
        missing = [make_field(name, kind) for name, kind in wanted if layer.fields().lookupField(name) == -1]
        if missing:
            if layer.isEditable():
                for field in missing:
                    if not layer.addAttribute(field):
                        raise RuntimeError(tr("cannot add field '{}'").format(field.name()))
            else:
                provider = layer.dataProvider()
                if not provider.addAttributes(missing):
                    raise RuntimeError(tr("cannot add fields: {}").format(", ".join(provider.errors())
                                                                          or tr("provider error")))
                layer.updateFields()
        return {name: layer.fields().lookupField(name) for name, _ in wanted}

    def applyMethodFromPreview(self, fid, method, level, spline=None):
        """Method chosen in the 3D view: it is set in the row of the table and saved at once in the
        layer (Base_meth / Base_z, and Base_ring / Base_stiff for a spline), so it is kept even
        without a new calculation. spline: (ring width, stiffness) of a spline base.
        Returns the note shown in the 3D view, or None when the row could not be changed."""
        dlg = self.dlg
        if dlg is None or not dlg.applyMethodToFid(fid, method, level):
            return None
        is_spline = method == BaseLevelOptions.SPLINE_RING and spline is not None
        if is_spline:
            dlg.setSplineParams(fid, *spline)
        layer = dlg.mFieldComboPolygon.currentLayer()
        set_note = tr("Method set in the table.")
        if level is not None:
            set_note = tr("Method and level ({:.3f} {}) set in the table.").format(level, dlg._unit_suffix)
        try:
            if layer is None or not provider_has_capability(layer.dataProvider(), "ChangeAttributeValues"):
                raise RuntimeError(tr("read-only layer"))
            wanted = [(BASE_METHOD_FIELD, "string"), (BASE_LEVEL_FIELD, "double")]
            if is_spline:
                wanted += [(BASE_RING_FIELD, "double"), (BASE_STIFF_FIELD, "double")]
            index = self._addMissingFields(layer, wanted)
            values = {index[BASE_METHOD_FIELD]: method.code,
                      index[BASE_LEVEL_FIELD]: level if method == BaseLevelOptions.MANUAL_BASE_LEVEL else NULL}
            if is_spline:
                values[index[BASE_RING_FIELD]] = float(spline[0])
                values[index[BASE_STIFF_FIELD]] = float(spline[1])
            if layer.isEditable():
                for field_index, value in values.items():
                    layer.changeAttributeValue(fid, field_index, value)
                return tr("Saved in the layer (edit mode: save the edits).")
            if not layer.dataProvider().changeAttributeValues({fid: values}):
                raise RuntimeError(", ".join(layer.dataProvider().errors()) or tr("provider error"))
            layer.reload()
        except Exception as exc:
            QgsMessageLog.logMessage("Saving the method of feature {} failed: {}".format(fid, exc),
                                     MESSAGE_CATEGORY, Qgis.Warning)
            return set_note + " " + tr("Not saved in the layer ({}): it will be at the next calculation.").format(exc)
        dlg.markFidStored(fid)
        return tr("Saved in the layer.")

    def buildLabelExpression(self, ctx):
        unit_label = VOLUME_UNITS[ctx["unit_key"]][0]
        decimals = ctx["decimals"]
        counting = ctx["counting"]

        def part(field_name, prefix):
            ref = QgsExpression.quotedColumnRef(field_name)
            text = "format_number({ref}, {d}) || {unit}".format(
                ref=ref, d=decimals, unit=QgsExpression.quotedString(" " + unit_label))
            if prefix:
                text = "{} || {}".format(QgsExpression.quotedString(prefix), text)
            return "if({ref} IS NULL, '', {text})".format(ref=ref, text=text)

        if counting == CountOptions.COUNT_ABOVE_AND_BELOW:
            volumes = "concat({}, '\\n', {})".format(part(ctx["name_pos"], "▲ "), part(ctx["name_neg"], "▼ "))
        elif counting == CountOptions.COUNT_ONLY_ABOVE:
            volumes = part(ctx["name_pos"], "")
        else:
            volumes = part(ctx["name_neg"], "")
        name_field = ctx.get("label_name_field")
        if not name_field or ctx["vector_layer"].fields().lookupField(name_field) == -1:
            return volumes
        # name (e.g. the material) on the first line, only when it is filled in
        name = "coalesce(to_string({}), '')".format(QgsExpression.quotedColumnRef(name_field))
        return "concat(if({name} = '', '', {name} || '\\n'), {volumes})".format(name=name, volumes=volumes)

    def applyVolumeLabels(self, ctx):
        layer = ctx["vector_layer"]
        settings = QgsPalLayerSettings()
        settings.isExpression = True
        settings.fieldName = self.buildLabelExpression(ctx)
        try:
            settings.placement = Qgis.LabelPlacement.OverPoint
        except AttributeError:
            settings.placement = QgsPalLayerSettings.OverPoint
        try:
            settings.multilineAlign = Qgis.LabelMultiLineAlignment.Center
        except AttributeError:
            settings.multilineAlign = QgsPalLayerSettings.MultiCenter

        text_format = QgsTextFormat()
        font = QFont()
        font.setBold(True)
        text_format.setFont(font)
        text_format.setSize(10)
        text_format.setColor(QColor(20, 20, 20))
        buffer = QgsTextBufferSettings()
        buffer.setEnabled(True)
        buffer.setSize(1.0)
        buffer.setColor(QColor(255, 255, 255))
        text_format.setBuffer(buffer)
        settings.setFormat(text_format)

        layer.setLabeling(QgsVectorLayerSimpleLabeling(settings))
        layer.setLabelsEnabled(True)
        layer.triggerRepaint()

    def updateOutputLog(self, results, ctx, task):
        unit_key = ctx["unit_key"]
        unit_label = VOLUME_UNITS[unit_key][0]
        decimals = ctx["decimals"]
        counting = ctx["counting"]
        locale = QLocale()

        def fmt(volume_m3):
            return "{} {}".format(locale.toString(convert_volume(volume_m3, unit_key), "f", decimals), unit_label)

        # only what the table does not show: warnings, problems of the polygons, and the total
        # (the volumes and the base of each polygon are in the table and its tooltips)
        self.appendLogLine("<b>{}</b> · {} · {}".format(datetime.now().strftime('%H:%M:%S'),
                                                        html.escape(ctx["vector_layer"].name()),
                                                        html.escape(ctx["height_layer"].name())))
        warnings = list(ctx["warnings"])
        if ctx["step_x"] > ctx["pixel_x"] * 1.0001 or ctx["step_y"] > ctx["pixel_y"] * 1.0001:
            warnings.append(tr("step larger than the DEM pixel, part of the DEM is not used."))
        for job in ctx["jobs"]:
            res = results.get(job.fid) or PolygonResult(job.fid, job.name, job.method)
            if not res.ok:
                warnings.append(tr("ID {}: not computed — {}").format(job.fid, res.error))
                continue
            if res.cells_inside and res.coverage < COVERAGE_WARNING_THRESHOLD:
                warnings.append(tr("ID {}: only {:.1f} % of the polygon has DEM data, volume underestimated.")
                                .format(job.fid, res.coverage * 100.0))
            for note in res.notes:
                warnings.append(tr("ID {}: {}").format(job.fid, note))
        for warning in warnings:
            self.appendLogLine("<span style='color:{};'>{}</span>".format(
                ERROR_COLOR, html.escape(tr("Warning: {}").format(warning))))
        ok = [results[job.fid] for job in ctx["jobs"] if job.fid in results and results[job.fid].ok]
        totals = []
        if counting.writes_above:
            totals.append(tr("above {}").format(fmt(sum(res.above_m3 for res in ok))))
        if counting.writes_below:
            totals.append(tr("below {}").format(fmt(sum(res.below_m3 for res in ok))))
        self.appendLogLine("<b>{}</b>".format(html.escape(tr("Total: {}").format(" · ".join(totals)))))
        self.appendLogLine()
        scroll_bar = self.dlg.logOutput.verticalScrollBar()
        scroll_bar.setValue(scroll_bar.maximum())

