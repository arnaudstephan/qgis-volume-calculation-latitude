    def reloadPolygonTable(self):
        if self.dlg is None:
            return
        layer = self.dlg.mFieldComboPolygon.currentLayer()
        if layer is None:
            self.dlg.populatePolygonTable(None, [])
            return
        fields = layer.fields()
        method_idx = fields.lookupField(BASE_METHOD_FIELD)
        level_idx = fields.lookupField(BASE_LEVEL_FIELD)
        ring_idx = fields.lookupField(BASE_RING_FIELD)
        stiff_idx = fields.lookupField(BASE_STIFF_FIELD)

        def number(feature, index):
            if index == -1:
                return None
            try:
                return float(feature.attribute(index))
            except (TypeError, ValueError):
                return None

        context = QgsExpressionContext()
        context.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(layer))
        expression = QgsExpression(layer.displayExpression() or "")
        has_expression = bool(layer.displayExpression()) and not expression.hasParserError()
        if has_expression:
            expression.prepare(context)

        rows = []
        for feature in layer.getFeatures():
            name = ""
            if has_expression:
                context.setFeature(feature)
                value = expression.evaluate(context)
                name = "" if value is None or value == NULL else str(value)
            method = None
            level = None
            if method_idx != -1:
                method = BaseLevelOptions.from_code(feature.attribute(method_idx))
            if method == BaseLevelOptions.MANUAL_BASE_LEVEL:
                level = number(feature, level_idx)
            rows.append({"fid": feature.id(), "name": name, "method": method, "level": level,
                         "ring": number(feature, ring_idx), "stiffness": number(feature, stiff_idx)})
        self.dlg.populatePolygonTable(layer.id(), rows)

