def _layer_filter(name):
    """Qgis.LayerFilter (QGIS >= 3.34) or QgsMapLayerProxyModel filter (older)."""
    layer_filter = getattr(Qgis, "LayerFilter", None)
    if layer_filter is not None and hasattr(layer_filter, name):
        return getattr(layer_filter, name)
    return getattr(QgsMapLayerProxyModel, name)


def _layer_filters(*names):
    """Combination of several layer filters, typed as flags (an int would hit a deprecated overload)."""
    value = _layer_filter(names[0])
    for name in names[1:]:
        value = value | _layer_filter(name)
    flags_type = getattr(Qgis, "LayerFilters", None) or getattr(QgsMapLayerProxyModel, "Filters", None)
    return flags_type(value) if flags_type is not None else value


