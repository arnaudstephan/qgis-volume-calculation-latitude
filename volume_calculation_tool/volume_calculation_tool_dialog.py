    def _fillSetMethodMenu(self, menu):
        """Selected rows: methods at the first level (the most frequent action).
        Checked rows / all rows: in sub-menus."""
        menu.clear()
        menu.setEnabled(not self._running)
        selected = self.selectedRows()
        if selected:
            title = menu.addAction(_plural(len(selected), tr("Set the {} selected row to:"),
                                           tr("Set the {} selected rows to:")).format(len(selected)))
            font = title.font()
            font.setBold(True)
            title.setFont(font)
            title.setEnabled(False)
            self._addMethodActions(menu, selected)
        else:
            hint = menu.addAction(tr("Select rows in the table to change only them"))
            hint.setEnabled(False)
        menu.addSeparator()
        for title, rows in ((tr("Checked rows"), self.checkedRows()),
                            (tr("All rows"), list(range(self.tablePolygons.rowCount())))):
            sub = menu.addMenu("{} ({})".format(title, len(rows)))
            sub.setToolTipsVisible(True)
            sub.setEnabled(bool(rows))
            self._addMethodActions(sub, rows)

    def _showTableContextMenu(self, pos):
        if self.tablePolygons.rowCount() == 0:
            return
        menu = QMenu(self)
        menu.setToolTipsVisible(True)
        row = self.tablePolygons.rowAt(pos.y())
