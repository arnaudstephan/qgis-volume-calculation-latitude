        table = self.tablePolygons
        table.blockSignals(True)  # a single refresh at the end instead of one per row
        for row in range(table.rowCount()):
            fid = table.item(row, COL_ID).data(Qt.ItemDataRole.UserRole)
            checked = fids is None or fid in fids
            table.item(row, COL_USE).setCheckState(Qt.CheckState.Checked if checked else Qt.CheckState.Unchecked)
        table.blockSignals(False)
        table.viewport().update()
        self._onCheckChanged()

