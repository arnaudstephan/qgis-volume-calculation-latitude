    # ---- visibility guard ----------------------------------------------------------
    # Qt also emits widget signals while it destroys a closed dialog (deleteLater, layers removed
    # from the project...): a Python slot reading a half-destroyed widget then crashes QGIS.
    # The slots that touch widgets therefore do nothing while the dialog is hidden, and the
    # state that depends on them is refreshed when the dialog is shown again.
    def _ifShown(self, function):
        def slot(*args):
            if self._shown:
                function(*args)
        return slot

