def suggested_cloud_resolution(layer):
    """About the mean point spacing, rounded up to 5 cm (at least 5 cm)."""
    try:
        count = layer.pointCount()
        extent = layer.extent()
        area = extent.width() * extent.height()
        if count > 0 and area > 0:
            spacing = math.sqrt(area / count)
            return max(0.05, math.ceil(spacing / 0.05) * 0.05)
    except Exception:
        pass
    return 0.1


class UserInputError(Exception):
    """Invalid input: shown as a warning, nothing is computed."""


def check_manual_levels(choices):
    """A 'Manual level' row without an entered level must not silently use a base at 0 m."""
    missing = [c for c in choices if c["method"] == BaseLevelOptions.MANUAL_BASE_LEVEL and c["level"] is None]
    if missing:
        names = ["{}{}".format(c["fid"], " – " + c["name"] if c["name"] else "") for c in missing]
        raise UserInputError(tr("Enter the manual level of: {} (column 'Manual level', in red).").format(
            ", ".join(names)))


def make_field(name, kind):
    """QgsField compatible with QGIS 3.x (QVariant) and >= 3.38 / 4.x (QMetaType)."""
    if Qgis.versionInt() >= 33800:
        from qgis.PyQt.QtCore import QMetaType
        field_type = QMetaType.Type.Double if kind == "double" else QMetaType.Type.QString
    else:
        from qgis.PyQt.QtCore import QVariant
        field_type = QVariant.Double if kind == "double" else QVariant.String
    field = QgsField(name, field_type)
    if kind == "string":
        field.setLength(10)
    return field


def provider_has_capability(provider, name):
    caps = provider.capabilities()
    enum = getattr(Qgis, "VectorProviderCapability", None)
    flag = getattr(enum, name, None) if enum is not None else None
    if flag is None:
        flag = getattr(QgsVectorDataProvider, name)
    return bool(caps & flag)


def crs_to_gdal_wkt(crs):
    try:
        return crs.toWkt(Qgis.CrsWktVariant.PreferredGdal)
    except AttributeError:
        return crs.toWkt(QgsCoordinateReferenceSystem.WKT_PREFERRED_GDAL)


