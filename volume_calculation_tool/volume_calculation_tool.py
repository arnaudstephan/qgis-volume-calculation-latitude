    def onHeightLayerChanged(self, layer):
        if self.dlg is None:
            return
        unit = "m"   # metric by default, until a layer gives its CRS unit
        is_cloud = isinstance(layer, QgsPointCloudLayer)
        self.dlg.setPointCloudMode(is_cloud)
        if is_cloud and layer.isValid() and layer.crs().isValid():
            unit = crs_unit_abbreviation(layer.crs())
        elif isinstance(layer, QgsRasterLayer) and layer.isValid() and layer.crs().isValid():
            unit = crs_unit_abbreviation(layer.crs())
        if is_cloud and layer.isValid():
            self.dlg.doubleSpinBoxCloudResolution.setValue(suggested_cloud_resolution(layer))
        elif isinstance(layer, QgsRasterLayer) and layer.isValid():
            pixel_x = abs(layer.rasterUnitsPerPixelX())
            pixel_y = abs(layer.rasterUnitsPerPixelY())
            if pixel_x > 0 and pixel_y > 0:
                # default: one sample per DEM pixel (exact pixel values, no resampling)
                self.dlg.setSamplingSteps(pixel_x, pixel_y)
        self.dlg.setBaseLevelUnitLabel(unit)

